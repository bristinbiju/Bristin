import type { Language } from '../context/LanguageContext';
import { getProjects } from './projects';
import { translations } from './translations';
import { isFilled } from './content';
import { LANGUAGES, OG_LOCALE, localizePath } from '../lib/locale';
import { imgUrl, ogUrl } from '../lib/images';

export const SITE_URL = 'https://bristin.world';
const SITE_NAME = 'Bristin Biju';

export interface PageMeta {
  lang: Language;
  title: string;
  description: string;
  /** Path from the site root, e.g. '/fr/work/gba'. */
  path: string;
  /** Same page in every language (for hreflang); empty for pages that shouldn't be indexed. */
  alternates: Partial<Record<Language, string>>;
  ogLocale: string;
  /** Absolute path of the 1200x630 share image (generated by `npm run images`). */
  image: string;
  noindex?: boolean;
  /** Above-the-fold image to preload in the static HTML (base path + sizes). */
  preloadImage?: { src: string; sizes: string };
}

/** `sizes` of the case-study cover: must match CaseStudyPage so the preload is reused. */
export const COVER_SIZES = '(min-width: 1200px) 1120px, 100vw';

const home: Record<Language, { title: string; description: string }> = {
  en: {
    title: 'Bristin Biju | Brand & Graphic Designer in Paris',
    description:
      'Paris-based brand and graphic designer with 4+ years of experience in branding, visual identity, graphic design and motion graphics.',
  },
  fr: {
    title: 'Bristin Biju | Graphiste & Designer de Marque à Paris',
    description:
      "Graphiste et designer de marque basé à Paris, plus de 4 ans d'expérience en branding, identité visuelle, design graphique et motion design.",
  },
};

const alternatesFor = (neutralPath: string) =>
  Object.fromEntries(LANGUAGES.map((l) => [l, localizePath(neutralPath, l)])) as Record<Language, string>;

/**
 * Title / description / URLs / share image for a page. Used in the browser
 * (usePageMeta) and at build time (scripts/build-meta.mjs), so both always agree.
 */
export function pageMeta(lang: Language, slug?: string): PageMeta {
  const base = { lang, ogLocale: OG_LOCALE[lang] };
  if (!slug) {
    return { ...base, ...home[lang], path: localizePath('/', lang), alternates: alternatesFor('/'), image: ogUrl('/og/home.jpg') };
  }
  const p = getProjects(lang).find((x) => x.slug === slug);
  if (!p) {
    // Unknown slug or URL (also the pre-rendered dist/404.html): noindex, no canonical/hreflang.
    const t = translations[lang].caseStudy;
    return {
      ...base,
      title: `${t.notFoundTitle} | ${SITE_NAME}`,
      description: t.notFoundText,
      path: localizePath('/', lang),
      alternates: {},
      image: ogUrl('/og/home.jpg'),
      noindex: true,
    };
  }
  const name = isFilled(p.text.title) ? p.text.title : `${p.name}: ${p.category}`;
  const client = isFilled(p.client) ? p.client : p.name;
  const description = isFilled(p.text.summary)
    ? p.text.summary
    : lang === 'fr'
      ? `${p.name} (${p.category.toLowerCase()}) pour ${client}, par Bristin Biju, graphiste et designer de marque à Paris.`
      : `${p.name}: ${p.category.toLowerCase()} work for ${client} by Bristin Biju, a brand and graphic designer in Paris.`;
  const neutral = `/work/${p.slug}`;
  return {
    ...base,
    title: `${name} | ${SITE_NAME}`,
    description,
    path: localizePath(neutral, lang),
    alternates: alternatesFor(neutral),
    image: ogUrl(`/og/${p.slug}.jpg`),
    preloadImage: { src: p.cover, sizes: COVER_SIZES },
  };
}

/**
 * schema.org Person for the home pages. Only verifiable facts: name, role,
 * site, city, and the profile links already published on the site.
 */
export function personJsonLd(lang: Language) {
  return {
    '@context': 'https://schema.org',
    '@type': 'Person',
    '@id': `${SITE_URL}/#person`,
    name: 'Bristin Biju',
    jobTitle: lang === 'fr' ? 'Graphiste & Designer de Marque' : 'Brand & Graphic Designer',
    url: SITE_URL,
    image: `${SITE_URL}${imgUrl('/images/about/photo', 800)}`,
    address: {
      '@type': 'PostalAddress',
      addressLocality: 'Paris',
      addressRegion: 'Île-de-France',
      addressCountry: 'FR',
    },
    knowsAbout: ['Brand Identity', 'Logo Design', 'Graphic Design', 'Typography', 'Art Direction', 'Motion Graphics', 'Digital Design'],
    sameAs: [
      'https://www.linkedin.com/in/bristin-biju-832a4a1a6',
      'https://www.instagram.com/bristinbiju/',
      'https://www.behance.net/bristinbiju',
    ],
  };
}
